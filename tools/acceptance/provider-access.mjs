// Writes docs/PROVIDER-ACCESS.md, the provider access register (ACC-05), from src/provider-access.json, the program
// registries and the provider acceptance ledger. Run after `npm run build`:
//   node tools/acceptance/provider-access.mjs           write the document
//   node tools/acceptance/provider-access.mjs --check   fail when the register is invalid or the document is stale
// It reads committed files only and never contacts a provider.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const root = fileURLToPath(new URL('../..', import.meta.url)),
  target = path.join(root, 'docs/PROVIDER-ACCESS.md');
const names = {
  google: 'Google Ads',
  meta: 'Meta',
  tiktok: 'TikTok',
  snapchat: 'Snapchat',
  linkedin: 'LinkedIn',
  x: 'X',
  microsoft: 'Microsoft Advertising',
  apple: 'Apple Ads',
  reddit: 'Reddit',
  dv360: 'Display & Video 360',
  ga4: 'Google Analytics 4',
  gtm: 'Google Tag Manager',
  gsc: 'Google Search Console',
  drive: 'Google Drive',
  sheets: 'Google Sheets',
  amazon: 'Amazon Ads',
  criteo: 'Criteo',
  adjust: 'Adjust',
  google_business: 'Google Business Profile',
};
const cell = value => String(value ?? '—').replaceAll('|', '\\|');

/** The document's text from the built register module and the committed action ledger. */
export async function providerAccessMarkdown() {
  const {registerProblems, providerAccessDocument, providerAccessRegister} = await import(
    pathToFileURL(path.join(root, 'dist/src/provider-access.js')).href
  );
  if (registerProblems.length) throw Error('Provider access register: ' + registerProblems.join('; '));
  const ledger = JSON.parse(
      fs.readFileSync(path.join(root, 'docs/implementation/ACTION-CONTRACT-COVERAGE.json'), 'utf8'),
    ),
    layers = ledger.acceptance_layers,
    providers = providerAccessDocument();
  for (const p of providers) if (!names[p.id]) throw Error('Name provider ' + p.id + ' in ' + import.meta.url);
  const lines = [
    '# Provider access register',
    '',
    'Generated by `node tools/acceptance/provider-access.mjs` from `src/provider-access.json`, the program registries',
    '(`src/conditional-programs.ts`, `src/discovery-programs.ts`) and the provider acceptance ledger',
    '(`src/acceptance-ledger.json`). Do not edit it by hand (ACC-05).',
    '',
    'It records, per provider, what the deployment holds as the owner declares it, each declaration with its date, the',
    'programs that gate the provider, and what owner-authorized live acceptance has recorded. A declaration is a',
    'statement, never a grant: AMCP still sends every request under every control, and the provider decides. AMCP never',
    'infers a cause from a refusal (a 403 stays `PROVIDER_ACCESS_DENIED` unless the provider names its code). The owner',
    'health view on Settings shows the same declarations live, beside each connected provider’s last successful sync, last',
    'sync refusal code and latest program observation.',
    '',
    '## Updating a declaration',
    '',
    '1. Edit the provider’s approval in `src/provider-access.json`: `status` is `approved`, `applied`, `denied` or',
    '   `not_needed` (or `undeclared`), `value` is a short level such as `Standard` (or `null`), and `declared_at` is the',
    '   day of the declaration. Never write a token, key, account or customer ID or e-mail address; the register refuses',
    '   them. Approval e-mails and tickets stay in the owner’s private evidence store.',
    '2. Run `npm run build`, then `node tools/acceptance/provider-access.mjs`, and commit both files.',
    '3. A declaration is confirmed again by its review date, ' +
      providerAccessRegister.stale_after_days +
      ' days after it was made; the owner health view marks it stale after that.',
    '',
    'Live acceptance results enter through the ledger, never by hand: each harness in `tools/acceptance/` writes a record',
    'whose rows `node tools/acceptance/ledger.mjs add <record.json>` validates and appends ([acceptance',
    'runbooks](acceptance/README.md)).',
    '',
    '## Evidence layers',
    '',
    'Counts over every action of the [action ledger](implementation/ACTION-CONTRACT-COVERAGE.json). Each layer is',
    'counted on its own; none implies another.',
    '',
    '| Layer | Actions |',
    '|---|---:|',
    '| Catalog (listed) | ' + layers.catalog + ' |',
    '| Pinned (an exact request mapping) | ' + layers.pinned + ' |',
    '| Locally qualified (a contract with tests) | ' + layers.locally_qualified + ' |',
    '| Read-accepted (ledger, current contract) | ' + layers.read_accepted + ' |',
    '| Write-accepted (ledger, current contract) | ' + layers.write_accepted + ' |',
    '| Refused (ledger) | ' + layers.refused + ' |',
    '| Stale (the contract changed since) | ' + layers.stale + ' |',
    '',
    '## Summary',
    '',
    '| Provider | API version | Offered | Approvals declared | Live programs | Discovery-only programs | Accepted reads | Accepted writes | Last ledger refusal |',
    '|---|---|---|---:|---:|---:|---:|---:|---|',
  ];
  for (const p of providers) {
    const declared = p.approvals.filter(a => a.status !== 'undeclared').length,
      live = p.programs.filter(x => x.mode === 'live_read').length,
      discovery = p.programs.filter(x => x.mode === 'discovery_only').length;
    lines.push(
      '| [' +
        names[p.id] +
        '](#' +
        names[p.id]
          .toLowerCase()
          .replace(/[^a-z0-9 -]/g, '')
          .replaceAll(' ', '-') +
        ') | ' +
        cell(p.api_version) +
        ' | ' +
        (p.offered ? 'yes' : 'no') +
        ' | ' +
        declared +
        ' of ' +
        p.approvals.length +
        ' | ' +
        live +
        ' | ' +
        discovery +
        ' | ' +
        p.acceptance.read_accepted +
        ' | ' +
        p.acceptance.write_accepted +
        ' | ' +
        (p.acceptance.last_refusal ? p.acceptance.last_refusal.checked_at.slice(0, 10) : '—') +
        ' |',
    );
  }
  for (const p of providers) {
    lines.push(
      '',
      '## ' + names[p.id],
      '',
      'Gateway `' + p.gateway + '`, API version ' + cell(p.api_version) + '.',
      '',
    );
    lines.push('| Approval | Status | Value | Declared | Confirm again by |', '|---|---|---|---|---|');
    for (const a of p.approvals)
      lines.push(
        '| ' + [cell(a.label), a.status, cell(a.value), cell(a.declared_at), cell(a.review_by)].join(' | ') + ' |',
      );
    if (p.programs.length) {
      lines.push('', 'Programs:', '');
      for (const x of p.programs)
        lines.push(
          '- **' +
            x.name +
            '** (`' +
            x.id +
            '`, ' +
            (x.mode === 'live_read' ? 'one bounded read with `program_check`' : 'discovery only, no request') +
            '). ' +
            x.access +
            ' Prerequisites: ' +
            x.prerequisites.map(t => t.replace(/\.$/, '')).join('; ') +
            '. [Reference](' +
            x.reference +
            '), read ' +
            x.checked_on +
            '.',
        );
    }
    const a = p.acceptance;
    lines.push(
      '',
      'Acceptance ledger: ' +
        (a.rows
          ? a.rows +
            ' rows over ' +
            a.actions +
            ' actions; read-accepted ' +
            a.read_accepted +
            ', write-accepted ' +
            a.write_accepted +
            ', refused ' +
            a.refused +
            ', stale ' +
            a.stale +
            '. Last accepted ' +
            (a.last_accepted_at ?? 'never') +
            (a.last_refusal
              ? '; last refusal ' +
                a.last_refusal.checked_at +
                ' (' +
                a.last_refusal.ticket +
                (a.last_refusal.status_codes.length ? ', HTTP ' + a.last_refusal.status_codes.join(', ') : '') +
                ')'
              : '') +
            '.'
          : 'no owner-authorized live acceptance is recorded; every action stays `unverified`.'),
    );
  }
  return lines.join('\n') + '\n';
}

async function main(argv) {
  const text = await providerAccessMarkdown();
  if (argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== text)
      throw Error(
        'docs/PROVIDER-ACCESS.md is out of date. Run npm run build, then node tools/acceptance/provider-access.mjs.',
      );
    console.log('docs/PROVIDER-ACCESS.md is current.');
    return;
  }
  fs.writeFileSync(target, text);
  console.log('Wrote docs/PROVIDER-ACCESS.md.');
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  main(process.argv.slice(2)).catch(e => {
    console.error(e.message);
    process.exitCode = 1;
  });
