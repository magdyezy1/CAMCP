// The status page (DOC-03): docs/STATUS.md, generated, so nobody types a status that can drift. It answers where AMCP
// stands from four sources, each generated or recorded elsewhere: the three-axis package status
// (docs/review/package-status.json, DOC-02 and owner decision D25), the product facts written from the code (tools/
// doc-facts.mjs, DOC-01), the provider access register (src/provider-access.json and the action ledger's acceptance
// layers, ACC-05) and the latest dated qualification record (docs/records/QUALIFICATION-*.md, QA-01). `npm run
// docs:index` writes it and `npm run docs:index:check` fails when it differs from what the sources say now.
import fs from 'node:fs';
import path from 'node:path';
import {inlineFacts} from './doc-facts.mjs';
import {dispositions, manualStates, nativeStates, statusFile} from './package-status.mjs';
import {frontMatterBlock, stripFrontMatter} from './docs-front-matter.mjs';

export const statusPage = 'docs/STATUS.md';
const ledgerFile = 'docs/implementation/ACTION-CONTRACT-COVERAGE.json',
  accessFile = 'src/provider-access.json',
  recordsFolder = 'docs/records';
const cell = v => String(v).replace(/\|/g, '\\|');
const grouped = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');

/** The newest qualification record (by the date in its name), or undefined when there is none. */
export function latestQualification(root) {
  const folder = path.join(root, recordsFolder);
  if (!fs.existsSync(folder)) return undefined;
  const records = fs
    .readdirSync(folder)
    .filter(file => /^QUALIFICATION-.*\d{4}-\d{2}-\d{2}\.md$/.test(file))
    .map(file => ({file, date: file.match(/(\d{4}-\d{2}-\d{2})\.md$/)[1]}))
    .sort((a, b) => b.date.localeCompare(a.date) || b.file.localeCompare(a.file));
  if (!records.length) return undefined;
  const {file, date} = records[0],
    text = stripFrontMatter(fs.readFileSync(path.join(folder, file), 'utf8')).replaceAll('\r\n', '\n'),
    title = /^# (.+)$/m.exec(text)?.[1].trim() ?? file,
    // The record's table of runs, as written (its first table under "## Runs").
    runs = /^## Runs\n\n((?:\|.*\n)+)/m.exec(text)?.[1].trimEnd().split('\n') ?? [];
  return {file: recordsFolder + '/' + file, date, title, runs};
}

/** The page's text from the sources and the code facts (the `facts` that tools/doc-facts.mjs collected). */
export function statusText(root, facts) {
  const status = JSON.parse(fs.readFileSync(path.join(root, statusFile), 'utf8')),
    ledger = JSON.parse(fs.readFileSync(path.join(root, ledgerFile), 'utf8')),
    access = JSON.parse(fs.readFileSync(path.join(root, accessFile), 'utf8')),
    values = inlineFacts(facts),
    packages = status.packages,
    count = (pick, states) =>
      states.map(v => v.replaceAll('_', ' ') + ' ' + packages.filter(p => pick(p) === v).length);
  const remainders = packages.flatMap(p => p.remainders),
    byDisposition = dispositions
      .map(d => [d, remainders.filter(r => r.disposition === d).length])
      .filter(([, n]) => n)
      .map(([d, n]) => d.replaceAll('_', ' ') + ' ' + n);
  const approvals = Object.values(access.providers).flatMap(p => p.approvals),
    approvalStates = [...new Set(approvals.map(a => a.status))].sort(),
    layers = ledger.acceptance_layers;
  const qualification = latestQualification(root);
  const lines = [
    frontMatterBlock({status: 'current', tier: 'operator', generated: 'tools/docs-status.mjs'}).trimEnd(),
    '',
    '# Status',
    '',
    'Where AMCP stands, generated by `npm run docs:index` from the package status, the code, the provider access',
    'register and the latest qualification record; `npm run docs:index:check` fails when it is out of date. What is',
    'implemented, area by area, is in [current readiness](CURRENT-READINESS.md); owner decisions are in',
    '[decisions](DECISIONS.md).',
    '',
    '## Packages on three axes',
    '',
    'Status as of ' +
      status.as_of +
      ' (owner decision D25). Each axis is counted on its own; a documented blocker never completes one.',
    '[Package status](review/PACKAGE-STATUS.md) lists every package, its remainders and the tests it cites.',
    '',
    '| Axis | Count |',
    '|---|---|',
    '| Source acceptance (of ' +
      packages.length +
      ') | ' +
      count(p => (p.source.met ? 'met' : 'not met'), ['met', 'not met']).join(' · ') +
      ' |',
    '| Native/live acceptance | ' + count(p => p.native.state, nativeStates).join(' · ') + ' |',
    '| Manual/deployed acceptance | ' + count(p => p.manual.state, manualStates).join(' · ') + ' |',
    '| Open remainders | ' + remainders.length + (byDisposition.length ? ': ' + byDisposition.join(' · ') : '') + ' |',
    '',
    '## The product today',
    '',
    'Written from the code and the committed ledgers (DOC-01), with `MIRROR_FLAGS` and `AMCP_PROVIDERS` unset.',
    '',
    '| Fact | Value |',
    '|---|---|',
    '| MCP tools, reviewed writes enabled | ' + values.tools_writes + ' |',
    '| MCP tools, read-only deployment | ' + values.tools_read_only + ' |',
    '| Reviewed write families | ' + values.reviewed_families + ' |',
    '| Campaign recipes | ' + values.campaign_recipes + ' (' + values.campaign_recipe_platforms + ') |',
    '| MCP guides | ' + values.mcp_guides + ' |',
    '| Providers offered | ' +
      values.providers_active +
      ' of ' +
      values.providers +
      (values.providers_parked ? ' (parked: ' + values.providers_parked + ')' : '') +
      ' |',
    '| Website platforms | ' + values.website_platforms + ' |',
    '| Action ledger | ' +
      values.ledger_actions +
      ' actions, ' +
      values.ledger_reviewed_writes +
      ' of them reviewed writes |',
    '',
    'The provider matrix and the tool table are in [current readiness](CURRENT-READINESS.md#6-providers).',
    '',
    '## Provider access and acceptance',
    '',
    'The [provider access register](PROVIDER-ACCESS.md) (ACC-05) records what the owner declares each deployment holds;',
    'a declaration is a statement, never a grant. The [acceptance runbooks](acceptance/README.md) say how each live',
    'acceptance is run.',
    '',
    '| Measure | Value |',
    '|---|---|',
    '| Provider approvals declared | ' +
      approvals.length +
      ' across ' +
      Object.keys(access.providers).length +
      ' providers: ' +
      approvalStates.map(s => s.replaceAll('_', ' ') + ' ' + approvals.filter(a => a.status === s).length).join(' · ') +
      ' |',
    '| Ledger actions: catalog · pinned · locally qualified | ' +
      [layers.catalog, layers.pinned, layers.locally_qualified].map(grouped).join(' · ') +
      ' |',
    '| Ledger actions: read-accepted · write-accepted · refused · stale | ' +
      [layers.read_accepted, layers.write_accepted, layers.refused, layers.stale].map(grouped).join(' · ') +
      ' |',
    '',
    '## Latest qualification',
    '',
  ];
  if (qualification)
    lines.push(
      '[' +
        cell(qualification.title) +
        '](' +
        path.posix.relative('docs', qualification.file) +
        '), ' +
        qualification.date +
        '.',
      ...(qualification.runs.length ? ['', ...qualification.runs] : []),
    );
  else lines.push('No qualification record in `docs/records/` yet.');
  return lines.join('\n') + '\n';
}

/** Writes or (check) compares docs/STATUS.md; returns the problems (an empty list passes). */
export function statusProblems(root, facts, {write = false} = {}) {
  let text;
  try {
    text = statusText(root, facts);
  } catch (error) {
    return ['status page: ' + error.message];
  }
  const target = path.join(root, statusPage),
    current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') : undefined;
  if (current === text) return [];
  if (write) {
    fs.writeFileSync(target, text);
    return [];
  }
  return [statusPage + ' is out of date. Run npm run build, then npm run docs:index.'];
}
