// Cloudflare's published edge address ranges, used by AMCP_CLIENT_IP_SOURCE=railway+cloudflare (SEC-01).
//
//   node tools/cloudflare-ranges.mjs            regenerate server/cloudflare-ranges.ts from the committed snapshot
//   node tools/cloudflare-ranges.mjs --check    fail when the module differs from the snapshot or a range is invalid
//   node tools/cloudflare-ranges.mjs --refresh  fetch Cloudflare's lists, rewrite the snapshot, then regenerate
//
// The default and --check modes are offline, so builds stay reproducible. --refresh is the only network step; it is a
// release-checklist task run by the owner, never part of a build, a test or `npm run check`.
import fs from 'node:fs';
import path from 'node:path';
import {isIP} from 'node:net';
import {fileURLToPath} from 'node:url';
import * as prettier from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const snapshotFile = 'generated/cloudflare-ranges.json',
  moduleFile = 'server/cloudflare-ranges.ts',
  sources = {ipv4: 'https://www.cloudflare.com/ips-v4', ipv6: 'https://www.cloudflare.com/ips-v6'};

/** The 128-bit value of an IPv6 address, or undefined. */
function ipv6Value(address) {
  if (isIP(address) !== 6 || address.includes('.') || address.includes('%')) return;
  const [head = '', tail] = address.split('::'),
    h = head ? head.split(':') : [],
    t = tail ? tail.split(':') : [],
    groups = tail === undefined ? h : [...h, ...Array(8 - h.length - t.length).fill('0'), ...t];
  return groups.reduce((value, group) => (value << 16n) | BigInt(parseInt(group, 16)), 0n);
}
function ipv4Value(address) {
  if (isIP(address) !== 4) return;
  return address.split('.').reduce((value, octet) => (value << 8n) | BigInt(Number(octet)), 0n);
}
/** Problems with one published range: an exact network address, a nonzero prefix and no host bits. */
export function cidrProblem(cidr, family) {
  if (typeof cidr !== 'string' || !/^[0-9a-f:.]+\/\d{1,3}$/.test(cidr)) return 'not a CIDR: ' + String(cidr);
  const [address, prefixText] = cidr.split('/'),
    prefix = Number(prefixText),
    bits = family === 'ipv4' ? 32 : 128,
    value = family === 'ipv4' ? ipv4Value(address) : ipv6Value(address);
  if (value === undefined) return 'not an ' + family + ' address: ' + cidr;
  if (prefix < 1 || prefix > bits) return 'prefix out of range: ' + cidr;
  if (value & ((1n << BigInt(bits - prefix)) - 1n)) return 'host bits are set: ' + cidr;
  return undefined;
}
export function snapshotProblems(snapshot) {
  const problems = [];
  if (!snapshot || typeof snapshot !== 'object') return ['The snapshot is not a JSON object.'];
  if (JSON.stringify(snapshot.sources) !== JSON.stringify(sources)) problems.push('The snapshot sources changed.');
  if (snapshot.retrieved_at !== null && !/^\d{4}-\d{2}-\d{2}T[\d:.]+Z$/.test(String(snapshot.retrieved_at)))
    problems.push('retrieved_at must be null or an ISO UTC timestamp.');
  for (const family of ['ipv4', 'ipv6']) {
    const list = snapshot[family];
    if (!Array.isArray(list) || !list.length || list.length > 200) {
      problems.push(family + ' must list between 1 and 200 ranges.');
      continue;
    }
    if (new Set(list).size !== list.length) problems.push(family + ' lists a range twice.');
    for (const cidr of list) {
      const problem = cidrProblem(cidr, family);
      if (problem) problems.push(family + ': ' + problem);
    }
  }
  return problems;
}
export async function renderModule(snapshot) {
  const source = `// Generated by tools/cloudflare-ranges.mjs from ${snapshotFile}; do not edit by hand.
// Refresh before a release with \`node tools/cloudflare-ranges.mjs --refresh\` (a release-checklist step).
/** When the snapshot was last fetched from Cloudflare's published lists by the tool; null when it never was. */
export const cloudflareRangesRetrievedAt: string | null = ${JSON.stringify(snapshot.retrieved_at)};
/** Cloudflare's published IPv4 edge ranges (${sources.ipv4}). */
export const cloudflareIpv4Ranges: readonly string[] = ${JSON.stringify(snapshot.ipv4)};
/** Cloudflare's published IPv6 edge ranges (${sources.ipv6}). */
export const cloudflareIpv6Ranges: readonly string[] = ${JSON.stringify(snapshot.ipv6)};
`;
  const config = (await prettier.resolveConfig(path.join(root, moduleFile))) ?? {};
  return prettier.format(source, {...config, parser: 'typescript'});
}
const readSnapshot = () => JSON.parse(fs.readFileSync(path.join(root, snapshotFile), 'utf8'));
async function fetchList(url, family) {
  const response = await fetch(url, {redirect: 'error', signal: AbortSignal.timeout(15000)});
  if (!response.ok) throw Error(url + ' returned HTTP ' + response.status);
  const text = await response.text();
  if (text.length > 65536) throw Error(url + ' returned an unexpectedly large list.');
  const list = text
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean);
  for (const cidr of list) {
    const problem = cidrProblem(cidr, family);
    if (problem) throw Error(url + ': ' + problem);
  }
  return list;
}
async function main(args) {
  if (args.some(a => !['--check', '--refresh'].includes(a)) || args.length > 1)
    throw Error('Usage: node tools/cloudflare-ranges.mjs [--check | --refresh]');
  let snapshot = readSnapshot();
  if (args[0] === '--refresh') {
    snapshot = {
      sources,
      retrieved_at: new Date().toISOString(),
      note: 'Fetched from the sources by tools/cloudflare-ranges.mjs --refresh.',
      ipv4: await fetchList(sources.ipv4, 'ipv4'),
      ipv6: await fetchList(sources.ipv6, 'ipv6'),
    };
  }
  const problems = snapshotProblems(snapshot);
  if (problems.length) throw Error(problems.join('\n'));
  const rendered = await renderModule(snapshot),
    target = path.join(root, moduleFile);
  if (args[0] === '--check') {
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
    if (current !== rendered) throw Error(moduleFile + ' differs from ' + snapshotFile + '. Run the generator.');
    console.log(JSON.stringify({checked: moduleFile, ipv4: snapshot.ipv4.length, ipv6: snapshot.ipv6.length}));
    return;
  }
  if (args[0] === '--refresh')
    fs.writeFileSync(path.join(root, snapshotFile), JSON.stringify(snapshot, null, 2) + '\n');
  fs.writeFileSync(target, rendered);
  console.log(JSON.stringify({written: moduleFile, ipv4: snapshot.ipv4.length, ipv6: snapshot.ipv6.length}));
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  main(process.argv.slice(2)).catch(error => {
    console.error(error.message);
    process.exitCode = 1;
  });
