import fs from 'node:fs';

// Explicit feed types, selected from independently captured official GAQL tables.
// New asset types do not become executable solely because Discovery adds them.
const types=['PAGE_FEED','DYNAMIC_EDUCATION','DYNAMIC_CUSTOM','DYNAMIC_HOTELS_AND_RENTALS','DYNAMIC_REAL_ESTATE','DYNAMIC_LOCAL','DYNAMIC_FLIGHTS','DYNAMIC_JOBS','DYNAMIC_TRAVEL','LOCATION','HOTEL_PROPERTY'];
const fields=JSON.parse(fs.readFileSync('tests/fixtures/google-asset-fields-v23.json','utf8')).fields;
const map=Object.fromEntries(types.map(type=>[type,Object.keys(fields).filter(field=>field.startsWith(type.toLowerCase()+'_asset.')&&fields[field].selectable).sort()]));
if(Object.values(map).some(fields=>!fields.length))throw Error('Missing selected feed asset fields.');
const output='src/google-asset-set-fields.ts',text='// Generated by tools/google-asset-set-fields.mjs from checked v23 GAQL field facts.\nexport const googleFeedAssetFields:Record<string,string[]>='+JSON.stringify(map,null,1)+';\n';
if(process.argv.includes('--check')){if(fs.readFileSync(output,'utf8')!==text)throw Error('Feed asset fields are stale.');}
else fs.writeFileSync(output,text);
console.log(JSON.stringify({types:types.length,fields:Object.values(map).flat().length}));
