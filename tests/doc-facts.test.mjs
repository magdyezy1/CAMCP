// DOC-01: the current pages stated counts and status by hand, and they drifted from the code: 143 registered families
// (the registry held 167), 24 Microsoft actions (28), ten MCP guides (13), "B25 open" after B25 was partial, two
// package triples in one page, a per-tenant audit chain the store never had, and a callback table and .env.example
// without Reddit or DV360. tools/doc-facts.mjs writes those facts from the code between markers, and
// `npm run docs:index:check` fails when a marker disagrees, a current page uses the retired vocabulary or a client
// variable the server reads is missing from .env.example.
