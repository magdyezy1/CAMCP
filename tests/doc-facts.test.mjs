test('.env.example names every website platform client variable, and the callback table lists every platform', t => {
  assert.deepEqual(environmentProblems(root, facts()), []);
  // Reddit's pair was missing (R25): removing it again is reported.
  const dir = copyTree(t);
  edit(dir, '.env.example', text => text.replace(/^AMCP_REDDIT_CLIENT_ID=\n/m, ''));
  assert.deepEqual(environmentProblems(dir, facts()), [
    '.env.example does not name AMCP_REDDIT_CLIENT_ID, which the server reads.',
  ]);
  const deploy = fs.readFileSync('docs/DEPLOY-RAILWAY.md', 'utf8'),
    table = /<!-- doc-facts:oauth-platforms:begin[^\n]*\n([\s\S]*?)<!-- doc-facts:oauth-platforms:end -->/.exec(
      deploy,
    )[1];
  assert.equal(table.split('\n').filter(line => /^\| (?!Platform \||---)/.test(line)).length, platforms.length);
  for (const p of platforms) {
    assert.ok(table.includes('`AMCP_' + p.env + '_CLIENT_ID`'), p.id);
    if (!p.authType) assert.ok(table.includes('/api/auth/' + p.id + '/callback`'), p.id);
  }
});

