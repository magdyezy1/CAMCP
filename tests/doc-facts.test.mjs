test('the threat model and architecture describe the one audit chain the store keeps, read per workspace', t => {
  // The documents said "hash chain per tenant"; appendAudit links each row to the last row of the whole table.
  const store = new Store(':memory:', Buffer.alloc(32, 9).toString('base64'));
  t.after(() => store.close());
  for (const tenant of ['workspace-a', 'workspace-b']) store.ensureTenant(tenant);
  store.appendAudit('workspace-a', 'a1', {event: 'first'});
  store.appendAudit('workspace-b', 'b1', {event: 'second'});
  store.appendAudit('workspace-a', 'a2', {event: 'third'});
  const a = store.audit('workspace-a'),
    b = store.audit('workspace-b');
  assert.deepEqual(
    a.map(row => row.request_id),
    ['a1', 'a2'],
  );
  assert.equal(a[1].previous_hash, b[0].hash, 'workspace A links to workspace B: one chain');
  assert.equal(store.verifyAudit(), true);
  for (const file of ['docs/review/THREAT-MODEL.md', 'docs/review/ARCHITECTURE.md']) {
    const text = fs.readFileSync(file, 'utf8');
    assert.doesNotMatch(text, /hash chain per tenant|per-tenant hash chain/i, file);
    assert.match(text, /one append-only hash chain across all workspaces/, file);
  }
});
