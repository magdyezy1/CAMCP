const root = process.cwd();
let collected;
/** The facts of the committed tree, collected once (a child process builds the tool surface). */
const facts = () => {
  if (!collected) {
    const files = docFacts(root);
    assert.deepEqual(files.problems, []);
    collected = files.facts;
  }
  return collected;
};
const temporary = t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'amcp-doc-facts-'));
  t.after(() => removeTestDirectory(directory, 'amcp-doc-facts-'));
  return directory;
};
/** A copy of the pages that hold markers, the root README and .env.example: what docFacts reads besides dist/. */
const copyTree = t => {
  const dir = temporary(t);
  for (const file of [...Object.keys(factFiles), '.env.example']) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), {recursive: true});
    fs.copyFileSync(path.join(root, file), path.join(dir, file));
  }
  return dir;
};
const edit = (dir, file, change) =>
  fs.writeFileSync(path.join(dir, file), change(fs.readFileSync(path.join(dir, file), 'utf8')));

test('the committed current pages hold exactly the facts the code and the ledgers give', () => {
  const {problems, changed} = docFacts(root, {facts: facts()});
  assert.deepEqual(problems, []);
  assert.deepEqual(changed, []);
});

test('a stale, missing, unknown, misplaced or malformed marker fails the check, and a hand edit of a block is stale', t => {
  const dir = copyTree(t),
    family = 'docs/ADDING-A-REVIEWED-FAMILY.md';
  assert.deepEqual(docFacts(dir, {facts: facts()}).problems, []);
  // The value the review found: 143 registered families.
  edit(dir, family, text => text.replace(/<!-- fact:reviewed_families -->\d+/, '<!-- fact:reviewed_families -->143'));
  assert.ok(
    docFacts(dir, {facts: facts()}).problems.includes(
      family + ' states facts the code no longer has. Run npm run build, then npm run docs:index.',
    ),
  );
  // Writing it again restores the code's value, so the check passes.
  assert.deepEqual(docFacts(dir, {facts: facts(), write: true}).problems, []);
  assert.deepEqual(docFacts(dir, {facts: facts()}).problems, []);
  // A literal in place of the marker.
  edit(dir, family, text => text.replace(/<!-- fact:reviewed_families -->(\d+)<!-- \/fact -->/, '$1'));
  assert.ok(
    docFacts(dir, {facts: facts()}).problems.includes(
      family + ': the fact reviewed_families is missing (it must come from a marker).',
    ),
  );
  const values = inlineFacts(facts()),
    blocks = renderBlocks(facts());
  const problems = text => applyFacts(text, family, values, blocks).problems;
  assert.match(problems('<!-- fact:reviewed_family -->1<!-- /fact -->').join('\n'), /unknown fact reviewed_family/);
  assert.match(problems('<!-- fact:reviewed_families -->1').join('\n'), /malformed documentation fact marker/);
  const misplaced =
    '<!-- doc-facts:tool-surface:begin (generated by npm run docs:index; do not edit) -->\n' +
    '<!-- doc-facts:tool-surface:end -->';
  assert.match(problems(misplaced).join('\n'), /the tool-surface block belongs in docs\/CURRENT-READINESS\.md/);
  // A block edited by hand is rewritten by the generator, so the check calls the page stale.
  edit(dir, family, text => text.replace('| Apple Ads | active | 2 |', '| Apple Ads | active | 3 |'));
  assert.ok(docFacts(dir, {facts: facts()}).changed.includes(family));
  // Removing a block entirely.
  edit(dir, 'docs/CURRENT-READINESS.md', text =>
    text.replace(/<!-- doc-facts:package-status:begin[\s\S]*?<!-- doc-facts:package-status:end -->/, ''),
  );
  assert.ok(
    docFacts(dir, {facts: facts()}).problems.includes(
      'docs/CURRENT-READINESS.md: the generated block package-status is missing.',
    ),
  );
});

test('current pages refuse the retired status vocabulary and hand-typed counts outside markers only', () => {
  const status = text => lintText(text, 'docs/X.md', statusRules),
    counts = text => lintText(text, 'docs/X.md', countRules);
  // The statements the review found in current pages (R25).
  for (const line of [
    'B25 conditional provider programs remains open.',
    'B21/B15/B16/B24 remain partial, B25 open; the matrix remains 13/14/1.',
    'The 28-package plan currently has 13 implemented, 15 partial and zero open.',
    'The whole-plan status remains 13 implemented / 14 partial / one open.',
    'The broader 13/15/0 audit remains visible.',
    "This record tracks the owner's request to finish the 14 partial packages.",
  ])
    assert.ok(status(line).length > 0, line);
  for (const line of [
    'All 143 reviewed families are registered (batch 33).',
    'MCP clients can load ten campaign/reporting guides through resources/list.',
    'Recipes cover three specified campaign types.',
    'The runtime exposes 26 tools with writes disabled and 28 with reviewed writes enabled.',
    'Every one of the 16 guided recipes has a fixture.',
  ])
    assert.ok(counts(line).length > 0, line);
  // Through a marker the same words pass; status words that describe the three axes pass too.
  assert.deepEqual(
    counts('All <!-- fact:reviewed_families -->170<!-- /fact --> reviewed families are registered.'),
    [],
  );
  assert.deepEqual(counts('With <!-- fact:tools_writes -->25<!-- /fact --> tools.'), []);
  assert.deepEqual(status('B25 is partial: its three program workflows exist.'), []);
  assert.deepEqual(status('Source acceptance (of 28): met 20 · not met 8.'), []);
  const block =
    '<!-- doc-facts:package-status:begin (generated by npm run docs:index; do not edit) -->\n' +
    '| B25 | 14 partial |\n' +
    '<!-- doc-facts:package-status:end -->\nB25 open\n';
  // Inside a block nothing is linted; the line after it is, under its own line number.
  assert.deepEqual(status(block), [
    'docs/X.md:4: "B25 open" — B25 is partial, not open: state package status through docs/review/PACKAGE-STATUS.md.',
  ]);
});

// The count rules read only README, CURRENT-READINESS, ADDING-A-REVIEWED-FAMILY and WORKSPACE-OPERATIONS, so a
// hand-typed count on any other current page (PRODUCT-WORKFLOWS, MICROSOFT-ADS, a guide AI clients read) passed.
test('every current page takes its counts from a marker; only a listed dated line keeps the count of its day', t => {
  const dir = copyTree(t),
    check = () => docFacts(dir, {facts: facts()}).problems,
    page = (file, text) => {
      fs.mkdirSync(path.dirname(path.join(dir, file)), {recursive: true});
      fs.writeFileSync(path.join(dir, file), text);
    };
  assert.deepEqual(check(), []);
  page('docs/PRODUCT-WORKFLOWS.md', '# Product workflows\n\nAMCP lists 26 tools.\n');
  assert.deepEqual(check(), [
    'docs/PRODUCT-WORKFLOWS.md:3: "26 tools" — a hand-typed tool count: use <!-- fact:tools_writes --> or <!-- fact:tools_read_only -->.',
  ]);
  page('docs/PRODUCT-WORKFLOWS.md', '# Product workflows\n');
  // A dated line that historyLines lists keeps its count; the status rules still read it.
  page('docs/OPERATIONS.md', '# Operations\n\n- Re-baseline after the wave 2 merges: 28 → 27 tools.\n');
  assert.deepEqual(check(), []);
  page('docs/OPERATIONS.md', '# Operations\n\n- Re-baseline after the wave 2 merges: 28 → 27 tools; B25 open.\n');
  assert.deepEqual(check(), [
    'docs/OPERATIONS.md:3: "B25 open" — B25 is partial, not open: state package status through docs/review/PACKAGE-STATUS.md.',
  ]);
  // An allowance whose line is gone is reported, so the list cannot outlive the history it excuses.
  page('docs/OPERATIONS.md', '# Operations\n');
  assert.deepEqual(check(), [
    'docs/OPERATIONS.md: historyLines in tools/doc-facts.mjs names "28 → 27 tools", which is no line of this current page any more; remove it.',
  ]);
  // The family rule's false positive on a current page: an RFC number before a comma is no count.
  assert.deepEqual(lintText('`client_revoke` (RFC 7009, family revoke)', 'docs/X.md', countRules), []);
  assert.equal(lintText('All 1,234 reviewed families are registered.', 'docs/X.md', countRules).length, 1);
  // In the repository every listed page is a current page that holds each listed line.
  const pages = currentPages(root);
  for (const [file, parts] of Object.entries(historyLines)) {
    assert.ok(pages.includes(file), file);
    for (const part of parts) assert.ok(fs.readFileSync(path.join(root, file), 'utf8').includes(part), part);
  }
});

// DOC-03 archived three dated reviews that historicalPages named, leaving redirect stubs at their old addresses.
test('the redirect stubs of moved documents are no current pages, and no historical page is a stub', t => {
  const {moves} = readMoves(root),
    pages = currentPages(root);
  for (const file of historicalPages) {
    assert.ok(fs.existsSync(path.join(root, file)), file + ' exists');
    assert.ok(!moves.has(file), file + ' moved (docs/moved.json); currentPages() leaves its stub out as a stub');
  }
  for (const file of moves.keys()) assert.ok(!pages.includes(file), file);
  for (const file of [
    'docs/CAPABILITY-REVIEW-2026-09-08.md',
    'docs/HARDENING-REVIEW.md',
    'docs/RECOMMENDATIONS-IMPLEMENTED.md',
  ])
    assert.ok(moves.has(file) && !pages.includes(file), file);
  const dir = temporary(t);
  for (const [file, text] of [
    ['README.md', '# Repo\n'],
    ['docs/GUIDE.md', '# Guide\n'],
    ['docs/OLD.md', '# Moved: Old\n'],
    ['docs/archive/OLD.md', '# Old\n\nB25 remains open.\n'],
    ['docs/moved.json', JSON.stringify({date: '2026-10-22', moved: {'docs/OLD.md': 'docs/archive/OLD.md'}})],
  ]) {
    fs.mkdirSync(path.dirname(path.join(dir, file)), {recursive: true});
    fs.writeFileSync(path.join(dir, file), text);
  }
  assert.deepEqual(currentPages(dir), ['README.md', 'docs/GUIDE.md']);
});

test('the documented tool surface equals listTools() of a read-only and a writes deployment', t => {
  // The page is generated with AMCP_PROVIDERS unset (parked providers are not listed); the comparison uses the same.
  const saved = process.env.AMCP_PROVIDERS;
  delete process.env.AMCP_PROVIDERS;
  t.after(() => (saved === undefined ? delete process.env.AMCP_PROVIDERS : (process.env.AMCP_PROVIDERS = saved)));
  const listed = allowWrites => {
    const store = new Store(':memory:', Buffer.alloc(32, 7).toString('base64'));
    t.after(() => store.close());
    const policy = allowWrites ? {allowWrites: true, maxBudgetChange: 0, requireBeforeState: true} : undefined;
    return new MirrorService(new Registry(), store, new NativeTransport(), undefined, policy).listTools();
  };
  const readOnly = listed(false),
    writes = listed(true);
  const page = fs.readFileSync('docs/CURRENT-READINESS.md', 'utf8'),
    block = /<!-- doc-facts:tool-surface:begin[^\n]*\n([\s\S]*?)<!-- doc-facts:tool-surface:end -->/.exec(page)[1];
  assert.match(block, new RegExp('A read-only deployment lists ' + readOnly.length + ' tools'));
  assert.match(block, new RegExp('a deployment with reviewed writes ' + writes.length + ' \\('));
  const rows = block
    .split('\n')
    .filter(line => line.startsWith('| `'))
    .map(line =>
      line
        .split(' | ')
        .map(c => c.replace(/^\| /, '').replace(/ \|$/, ''))
        .map(c => c.replace(/^`|`$/g, '')),
    );
  assert.deepEqual(
    rows.map(r => r[0]),
    [...new Set([...writes.map(t => t.name), ...readOnly.map(t => t.name)])],
  );
  const yes = v => (v ? 'yes' : 'no');
  for (const [name, title, ...hints] of rows) {
    const w = writes.find(t => t.name === name),
      r = readOnly.find(t => t.name === name);
    const both = (a, b) => a + (a === b ? '' : ' (' + b + ')');
    assert.equal(title, both(w.title, r.title), name);
    assert.deepEqual(
      hints,
      ['readOnlyHint', 'destructiveHint', 'idempotentHint', 'openWorldHint'].map(k =>
        both(yes(w.annotations[k]), yes(r.annotations[k])),
      ),
      name,
    );
  }
});

test("the generated facts do not depend on the generating process's environment", t => {
  // The Railway build and a Windows checkout must compute the same bytes: the collector gives the child a fixed
  // environment, so the parked providers, another LinkedIn version or MIRROR_FLAGS of the parent change nothing.
  const names = ['AMCP_PROVIDERS', 'AMCP_LINKEDIN_API_VERSION', 'MIRROR_FLAGS', 'MIRROR_ALLOW_WRITES'],
    saved = Object.fromEntries(names.map(n => [n, process.env[n]]));
  t.after(() => {
    for (const n of names)
      if (saved[n] === undefined) delete process.env[n];
      else process.env[n] = saved[n];
  });
  const clean = collectCodeFacts(root);
  Object.assign(process.env, {
    AMCP_PROVIDERS: 'criteo,woocommerce,amazon',
    AMCP_LINKEDIN_API_VERSION: '202510',
    MIRROR_FLAGS: '{"compactSchemas":true,"compactDescriptions":false}',
    MIRROR_ALLOW_WRITES: 'true',
  });
  assert.deepEqual(collectCodeFacts(root), clean);
  // The parked providers stay unlisted, as a deployment without AMCP_PROVIDERS lists them.
  assert.ok(!clean.tools.writes.tools.some(tool => tool.name === 'criteo_native_action'));
});

